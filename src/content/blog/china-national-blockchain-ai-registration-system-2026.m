China has taken another significant step in shaping its digital technology landscape. On November 9, 2026, the country's Cyberspace Administration officially launched a new national registration platform covering blockchain services, generative artificial intelligence and several other emerging technologies.

The move brings previously separate registration processes under one centralized online system, giving businesses and the public a single place to submit and search relevant filing information.

The announcement is attracting attention across the global technology and cryptocurrency industries, particularly as governments increasingly look to establish rules for blockchain and AI development.

---

## China Launches One Platform for Blockchain and AI

The new platform is officially called the Internet New Technology and New Application Information Service Filing System.

According to China's Cyberspace Administration, the system supports integrated registration for four major areas:

- Generative artificial intelligence
- Algorithms
- Deep synthesis technologies
- Blockchain information services

The platform went live on November 9, replacing two older systems: the Internet Information Service Algorithm Filing System and the Blockchain Information Service Filing Management System.

The new portal is available at:

**https://beian.cac.gov.cn**

The consolidation is designed to make registration and information searches more convenient for companies and members of the public.

